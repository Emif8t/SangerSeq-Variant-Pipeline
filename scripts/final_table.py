# SAVE FINAL TABLE
# ============================================================

def save_final_table(
    final_df: pd.DataFrame,
    output_folder: str,
) -> str:
    """
    Save the final annotated variant table.

    Parameters
    ----------
    final_df : pandas.DataFrame
        Final variant dataframe.

    output_folder : str
        Directory where the table will be saved.

    Returns
    -------
    str
        Path to the saved CSV file.
    """

    output_path = Path(
        output_folder
    )

    output_path.mkdir(
        parents=True,
        exist_ok=True,
    )

    output_file = (
        output_path
        / "Final_Annotated_Variants.csv"
    )

    final_df.to_csv(
        output_file,
        index=False,
    )

    print(
        "=" * 70
    )

    print(
        "Final variant table saved to:"
    )

    print(
        output_file
    )

    print()

    print(
        f"Final number of variants: "
        f"{len(final_df)}"
    )

    print()

    return str(output_file)